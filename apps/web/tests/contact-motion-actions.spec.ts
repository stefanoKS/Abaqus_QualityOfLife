import { expect, test } from './fixtures'
import type { Revision } from '../src/api'

test('motion edits preserve saved contact and review actions explain their state', async ({ page, request }) => {
  const revision: Revision = await (
    await request.post('/api/projects', { data: { name: 'Contact persistence', example: true } })
  ).json()
  await page.goto('/#workspace/' + revision.id)
  const workflow = page.getByRole('navigation', { name: 'Workflow' })
  await workflow.locator('[data-stage="contact"]').click()
  const friction = page.getByLabel('Friction coefficient')
  const describedBy = await friction.getAttribute('aria-describedby')
  expect(describedBy).toBeTruthy()
  await expect(page.locator(`[id="${describedBy}"]`)).toHaveText('Dimensionless coefficient, from 0 to 5 (inclusive).')
  for (const value of ['0', '0.3', '1', '2.5', '5']) {
    await friction.fill(value)
    await friction.press('Tab')
    await expect(friction).toHaveValue(value)
  }
  for (const invalid of ['-1', '5.1']) {
    await friction.fill(invalid)
    await friction.press('Tab')
    await expect(page.getByText('Enter a value within the permitted range.')).toBeVisible()
    await friction.press('Escape')
  }
  await friction.fill('')
  await friction.press('Tab')
  await expect(page.getByText('This numeric field is required.')).toBeVisible()
  await friction.press('Escape')
  await friction.fill('0.7')
  await friction.press('Tab')
  await expect(workflow.locator('[data-stage="contact"]')).toHaveAttribute('data-state', 'incomplete')
  await page.getByRole('button', { name: 'Save revision' }).click()
  await expect(page.locator('.crumb')).toContainText('Revision 02')
  await expect(workflow.locator('[data-stage="contact"]')).toHaveAttribute('data-state', 'complete')
  await workflow.locator('[data-stage="motion"]').click()
  const travel = page.getByLabel('Prescribed Y travel (mm)')
  await expect(travel).toHaveValue('-10')
  await travel.fill('')
  await workflow.locator('[data-stage="contact"]').click()
  await expect(travel).toBeVisible()
  await travel.press('Escape')
  await travel.fill('0')
  await travel.press('Tab')
  await expect(workflow.locator('[data-stage="contact"]')).toHaveAttribute('data-state', 'complete')
  await page.getByLabel('Analysis mode').selectOption('body_then_door')
  await page.getByLabel('Body initial Y offset (mm)').fill('0.2')
  await page.getByLabel('Body initial Y offset (mm)').press('Tab')
  await page.getByLabel('Body travel (mm, signed)').fill('2')
  await page.getByLabel('Body travel (mm, signed)').press('Tab')
  await page.getByLabel('Body seating duration (s)').fill('2')
  await page.getByLabel('Body seating duration (s)').press('Tab')
  await expect(workflow.locator('[data-stage="contact"]')).toHaveAttribute('data-state', 'complete')
  await page.getByLabel('Analysis mode').selectOption('door_only')
  await travel.fill('-6')
  await travel.press('Tab')
  await expect(workflow.locator('[data-stage="contact"]')).toHaveAttribute('data-state', 'complete')
  await workflow.locator('[data-stage="contact"]').click()
  await expect(friction).toHaveValue('0.7')
  await page.locator('.lang-button').click()
  await expect(page.getByText('摩擦係数は無次元です。0以上5以下で入力してください。')).toBeVisible()
  await expect(page.getByLabel('摩擦係数')).toHaveValue('0.7')
  await page.locator('.lang-button').click()
  await page.getByRole('button', { name: 'Save revision' }).click()
  await expect(page.locator('.crumb')).toContainText('Revision 03')
  await page.reload()
  await expect(workflow.locator('[data-stage="contact"]')).toHaveAttribute('data-state', 'complete')
  await workflow.locator('[data-stage="contact"]').click()
  await expect(friction).toHaveValue('0.7')
  const currentId = page.url().split('/').pop()!
  const saved = (await (await request.get('/api/revisions/' + currentId)).json()) as Revision
  expect(saved.setup.contact).toEqual({ normal: 'hard', scope: 'all_exterior', friction: 0.7 })
  expect(saved.setup.motion.travel).toBe(-6)
  await workflow.locator('[data-stage="review"]').click()
  const actions = page.getByTestId('review-actions')
  await expect(actions.getByRole('button', { name: 'Prepare input deck' })).toBeDisabled()
  await expect(actions.getByRole('button', { name: 'Submit Abaqus analysis' })).toBeDisabled()
  const prepare = (await actions.locator('.review-prepare').boundingBox())!
  const submit = (await actions.locator('.review-submit').boundingBox())!
  expect(prepare.x).toBeLessThan(submit.x)
  await page.setViewportSize({ width: 700, height: 900 })
  const prepareNarrow = (await actions.locator('.review-prepare').boundingBox())!
  const submitNarrow = (await actions.locator('.review-submit').boundingBox())!
  expect(prepareNarrow.y).toBeLessThan(submitNarrow.y)
})
